package com.mailersend.sdk.blocklistmonitoring;

import java.io.IOException;

import com.google.gson.TypeAdapter;
import com.google.gson.stream.JsonReader;
import com.google.gson.stream.JsonToken;
import com.google.gson.stream.JsonWriter;

/**
 * Reads the blocklisted count, which the create response returns as a boolean.
 */
class BlocklistedCountAdapter extends TypeAdapter<Integer> {

    @Override
    public void write(JsonWriter out, Integer value) throws IOException {
        out.value(value);
    }

    @Override
    public Integer read(JsonReader in) throws IOException {
        if (in.peek() == JsonToken.BOOLEAN) {
            return in.nextBoolean() ? 1 : 0;
        }

        return in.nextInt();
    }
}
